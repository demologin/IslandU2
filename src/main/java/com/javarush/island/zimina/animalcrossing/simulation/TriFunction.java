package com.javarush.island.zimina.animalcrossing.simulation;

/**
 * Функциональный интерфейс, представляющий функцию с тремя входными
 * параметрами и одним результатом. Аналог BiFunction, но для трёх аргументов —
 * используется для создания животных по координатам и конфигурации вида.
 *
 * @param <A> тип первого параметра
 * @param <B> тип второго параметра
 * @param <C> тип третьего параметра
 * @param <R> тип результата
 */
@FunctionalInterface
public interface TriFunction<A, B, C, R> {

    /**
     * Применяет функцию к трём аргументам.
     *
     * @param a первый аргумент
     * @param b второй аргумент
     * @param c третий аргумент
     * @return результат применения функции
     */
    R apply(A a, B b, C c);
}